export function searchCities(query: string) {
  const q = query
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();
  const aliases: Record<string, string> = {
    bangalore: 'bengaluru',
    bombay: 'mumbai',
    nyc: 'nyc',
    'new delhi': 'delhi',
    calcutta: 'kolkata',
    saigon: 'ho-chi-minh',
  };
  return CITIES.filter(
    (c) =>
      c.id === aliases[q] ||
      `${c.name} ${c.country} ${c.id}`
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .toLowerCase()
        .includes(q),
  );
}
